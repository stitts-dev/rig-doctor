#!/usr/bin/env bash
# Shared helpers for the Rig Doctor relay scripts. Sourced, never run directly.

CONF_DIR=${RIG_RELAY_CONF_DIR:-/etc/rig-relay}
LIB_DIR=${RIG_RELAY_LIB_DIR:-/usr/local/lib/rig-relay}
WG_IF=wg0
WG_CONF=/etc/wireguard/${WG_IF}.conf
NFT_TABLE=rig_relay
# Tunnel subnet: relay is .1, clients get .2-.254.
SUBNET_BASE=${RIG_RELAY_SUBNET_BASE:-10.66.66}
SUBNET="${SUBNET_BASE}.0/24"
RIPESTAT_URL='https://stat.ripe.net/data/announced-prefixes/data.json?resource=AS'
# Refuse a prefix list shorter than this. AS6507 announces ~40 IPv4 prefixes,
# so a tiny list means the lookup broke, not that Riot shrank.
MIN_PREFIXES=${RIG_RELAY_MIN_PREFIXES:-5}
API_DIR=$CONF_DIR/api

log() { printf '[rig-relay] %s\n' "$*" >&2; }
die() { printf '[rig-relay] error: %s\n' "$*" >&2; exit 1; }

require_root() { [ "$(id -u)" -eq 0 ] || die "run as root (sudo)"; }

load_env() {
  # shellcheck disable=SC1091
  [ -f "$CONF_DIR/relay.env" ] && . "$CONF_DIR/relay.env"
  return 0
}

# Reads CIDRs (one per line, any order, IPv4 and IPv6 mixed) on stdin and
# prints the collapsed IPv4 set. The tunnel is IPv4-only.
collapse_ipv4() {
  python3 -I -c '
import ipaddress, sys
nets = []
for line in sys.stdin:
    line = line.strip()
    if not line or line.startswith("#"):
        continue
    net = ipaddress.ip_network(line, strict=False)
    if net.version == 4:
        nets.append(net)
for net in ipaddress.collapse_addresses(nets):
    print(net)
'
}

# Prints the collapsed IPv4 prefixes announced by an ASN, from RIPEstat.
fetch_asn_prefixes() {
  local asn=$1 json
  json=$(curl -fsS --retry 3 --max-time 30 "${RIPESTAT_URL}${asn}") ||
    die "could not reach RIPEstat for AS${asn}"
  jq -r '.data.prefixes[].prefix' <<<"$json" | collapse_ipv4
}

# Writes a validated prefix list to $2 from source $1 (an ASN number or a file).
# The old list is kept if the new one is too short.
update_prefix_file() {
  local src=$1 dest=$2 tmp count
  tmp=$(mktemp)
  if [ -f "$src" ]; then
    collapse_ipv4 <"$src" >"$tmp"
  else
    fetch_asn_prefixes "$src" >"$tmp"
  fi
  count=$(grep -c . "$tmp" || true)
  if [ "$count" -lt "$MIN_PREFIXES" ]; then
    rm -f "$tmp"
    die "got $count prefixes (< $MIN_PREFIXES); keeping the existing list"
  fi
  install -m 0644 "$tmp" "$dest"
  rm -f "$tmp"
  log "prefix list: $count IPv4 prefixes"
}

# Prints the nftables ruleset. Args: wan_iface prefix_file
render_firewall() {
  local wan=$1 prefixes=$2 elements
  elements=$(paste -sd, "$prefixes" | sed 's/,/, /g')
  cat <<NFT
# Generated by rig-relay. Do not edit; re-run setup.sh or rig-relay-refresh.
table inet $NFT_TABLE
delete table inet $NFT_TABLE
table inet $NFT_TABLE {
  set riot4 {
    type ipv4_addr
    flags interval
    auto-merge
    elements = { $elements }
  }

  # Clients may ping the relay (latency proof). Nothing else on the relay is
  # reachable through the tunnel, including SSH.
  chain input {
    type filter hook input priority filter - 1; policy accept;
    iifname "$WG_IF" ct state established,related accept
    iifname "$WG_IF" icmp type echo-request accept
    iifname "$WG_IF" counter drop comment "tunnel to relay"
  }

  # Tunnel traffic may only exit to game server ranges.
  chain forward {
    type filter hook forward priority filter - 1; policy accept;
    iifname "$WG_IF" oifname "$wan" ip saddr $SUBNET ip daddr @riot4 counter accept comment "game traffic"
    iifname "$WG_IF" counter drop comment "non-game egress"
    oifname "$WG_IF" iifname "$wan" ct state established,related accept
    oifname "$WG_IF" counter drop comment "unsolicited inbound"
  }

  chain postrouting {
    type nat hook postrouting priority srcnat; policy accept;
    oifname "$wan" ip saddr $SUBNET counter masquerade
  }
}
NFT
}

# Hosts with ufw or Docker set the iptables FORWARD policy to DROP, which also
# drops tunnel traffic. Accept wg0 there; the nft forward chain above still
# limits egress to game ranges because a drop in any hook is final.
iptables_forward() {
  local action=$1 dir
  command -v iptables >/dev/null || return 0
  for dir in -i -o; do
    if [ "$action" = up ]; then
      iptables -C FORWARD "$dir" "$WG_IF" -j ACCEPT 2>/dev/null ||
        iptables -I FORWARD 1 "$dir" "$WG_IF" -j ACCEPT
    else
      while iptables -D FORWARD "$dir" "$WG_IF" -j ACCEPT 2>/dev/null; do :; done
    fi
  done
}

# Prints a client (peer) config. Args: name ip client_privkey
render_client_conf() {
  local name=$1 ip=$2 privkey=$3 allowed
  # The relay's tunnel address is included so clients can ping it for latency.
  allowed=$( (echo "${SUBNET_BASE}.1/32"; cat "$CONF_DIR/riot4.txt") | paste -sd, - | sed 's/,/, /g')
  cat <<CONF
# Rig Doctor relay client: $name
# Split tunnel: only game server ranges (AS${ASN}) and the relay go through it.
[Interface]
PrivateKey = $privkey
Address = $ip/32

[Peer]
PublicKey = $(cat "$CONF_DIR/server.pub")
Endpoint = $ENDPOINT:$PORT
AllowedIPs = $allowed
PersistentKeepalive = 25
CONF
}

# Writes wg0.conf from the interface settings plus one file per peer in
# $CONF_DIR/peers. Prints "changed" if the file content changed.
write_wg_conf() {
  local tmp f
  tmp=$(mktemp)
  {
    echo "# Generated by rig-relay. Add peers with rig-relay-add-peer."
    echo "[Interface]"
    echo "Address = ${SUBNET_BASE}.1/24"
    echo "ListenPort = $PORT"
    echo "PrivateKey = $(cat "$CONF_DIR/server.key")"
    echo "PostUp = $LIB_DIR/firewall.sh up"
    echo "PostDown = $LIB_DIR/firewall.sh down"
    for f in "$CONF_DIR"/peers/*.conf; do
      [ -e "$f" ] || continue
      echo
      cat "$f"
    done
  } >"$tmp"
  mkdir -p /etc/wireguard
  if ! cmp -s "$tmp" "$WG_CONF"; then
    install -m 0600 "$tmp" "$WG_CONF"
    echo changed
  fi
  rm -f "$tmp"
}

# Applies peer changes to a running interface without dropping sessions.
sync_peers() {
  if ip link show "$WG_IF" >/dev/null 2>&1; then
    wg syncconf "$WG_IF" <(wg-quick strip "$WG_IF")
  fi
}

# Prints the host firewall: on the WAN interface only SSH, the WireGuard port,
# the relay API port, ping/ICMPv6 and DHCP replies get in. Other interfaces are
# untouched. Args: wan_iface wg_port ssh_ports (comma-separated) api_port
render_host_firewall() {
  local wan=$1 wg_port=$2 ssh=$3 api=$4
  cat <<NFT
# Generated by rig-relay. Do not edit; re-run setup.sh.
table inet ${NFT_TABLE}_host
delete table inet ${NFT_TABLE}_host
table inet ${NFT_TABLE}_host {
  chain input {
    type filter hook input priority filter - 2; policy accept;
    iifname != "$wan" accept
    ct state established,related accept
    ct state invalid drop
    meta l4proto icmp accept
    meta l4proto ipv6-icmp accept
    udp dport { 68, 546 } accept comment "DHCP replies"
    tcp dport { $ssh } accept comment "ssh"
    udp dport $wg_port accept comment "wireguard"
    tcp dport $api accept comment "relay api"
    counter drop comment "wan default deny"
  }
}
NFT
}

# Creates the API's self-signed TLS certificate for the endpoint, or keeps the
# existing one if it already names that endpoint. Invites pin this certificate.
# It is an end-entity cert (CA:FALSE), which strict TLS clients require.
ensure_api_cert() {
  local host=$1 san cnf
  if [[ $host =~ ^[0-9.]+$ ]]; then san="IP:$host"; else san="DNS:$host"; fi
  mkdir -p "$API_DIR/invites"
  chmod 0700 "$API_DIR" "$API_DIR/invites"
  if [ -s "$API_DIR/tls.crt" ] && [ "$(cat "$API_DIR/tls.san" 2>/dev/null)" = "$san" ]; then
    return 0
  fi
  log "creating API certificate for $san"
  cnf=$(mktemp)
  cat >"$cnf" <<CNF
[req]
distinguished_name = dn
prompt = no
x509_extensions = ext
[dn]
CN = rig-relay
[ext]
basicConstraints = critical, CA:FALSE
keyUsage = critical, digitalSignature
extendedKeyUsage = serverAuth
subjectAltName = $san
CNF
  (umask 077 && openssl req -x509 -newkey ec -pkeyopt ec_paramgen_curve:prime256v1 -nodes \
    -days 3650 -config "$cnf" -keyout "$API_DIR/tls.key" -out "$API_DIR/tls.crt" 2>/dev/null) ||
    { rm -f "$cnf"; die "could not create the API certificate"; }
  rm -f "$cnf"
  chmod 0644 "$API_DIR/tls.crt"
  echo "$san" >"$API_DIR/tls.san"
}
