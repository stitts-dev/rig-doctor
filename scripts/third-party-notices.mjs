// Writes desktop/src-tauri/THIRD-PARTY-NOTICES.txt: every Rust crate built into the Windows and
// macOS apps and every npm package in the frontend's production dependencies, with the license
// text each one ships. The installers bundle the file. Identical license texts are printed once.
//
//   node scripts/third-party-notices.mjs          write the file
//   node scripts/third-party-notices.mjs --check  exit 1 when the file is out of date (CI)
//
// Needs `cargo` and `pnpm`, with `pnpm install` already run in desktop/.

import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const desktop = join(root, "desktop");
const tauri = join(desktop, "src-tauri");
const out = join(tauri, "THIRD-PARTY-NOTICES.txt");
// The platforms the installers ship for.
const TARGETS = ["x86_64-pc-windows-msvc", "aarch64-apple-darwin"];
const LICENSE_FILE = /^(licen[cs]e|copying|notice|unlicense)([-._].*)?$/i;

const run = (cmd, args, cwd) => execFileSync(cmd, args, { cwd, encoding: "utf8", maxBuffer: 256 * 1024 * 1024, shell: process.platform === "win32" });

/** License files in a package folder, as [name, text], sorted by name. */
function licenseFiles(dir, extra) {
  const names = new Set(existsSync(dir) ? readdirSync(dir).filter((n) => LICENSE_FILE.test(n) && statSync(join(dir, n)).isFile()) : []);
  if (extra && existsSync(join(dir, extra))) names.add(extra);
  return [...names].sort().map((n) => [n, readFileSync(join(dir, n), "utf8").replace(/\r\n/g, "\n").trim()]);
}

/** Crates reached from the app through normal (not build or dev) dependencies on one target. */
function cratesFor(target) {
  const meta = JSON.parse(run("cargo", ["metadata", "--locked", "--format-version", "1", "--filter-platform", target], tauri));
  const nodes = new Map(meta.resolve.nodes.map((n) => [n.id, n]));
  const seen = new Set();
  const stack = [meta.resolve.root];
  while (stack.length) {
    const id = stack.pop();
    if (seen.has(id)) continue;
    seen.add(id);
    for (const d of nodes.get(id)?.deps ?? []) if (d.dep_kinds.some((k) => k.kind === null)) stack.push(d.pkg);
  }
  seen.delete(meta.resolve.root);
  return meta.packages.filter((p) => seen.has(p.id));
}

const entries = new Map();
for (const target of TARGETS) {
  for (const p of cratesFor(target)) {
    const key = `crate ${p.name} ${p.version}`;
    if (!entries.has(key)) entries.set(key, { title: `${p.name} ${p.version} (Rust crate)`, license: p.license ?? "see license file", url: p.repository ?? "", files: licenseFiles(dirname(p.manifest_path), p.license_file) });
  }
}
const npm = JSON.parse(run("pnpm", ["licenses", "list", "--prod", "--json"], desktop));
for (const pkgs of Object.values(npm)) {
  for (const p of pkgs) {
    p.versions.forEach((v, i) => {
      const key = `npm ${p.name} ${v}`;
      if (!entries.has(key)) entries.set(key, { title: `${p.name} ${v} (npm package)`, license: p.license, url: p.homepage ?? "", files: licenseFiles(p.paths[i] ?? p.paths[0]) });
    });
  }
}

const sorted = [...entries.values()].sort((a, b) => (a.title < b.title ? -1 : 1));
const texts = new Map();
const lines = [
  "Rig Doctor Globe: third-party notices",
  "",
  "This app includes the open-source software listed below. Each entry names the package, its",
  "license, and the license text it ships. Identical texts are printed once, at the end, and",
  "referred to by number. Generated by scripts/third-party-notices.mjs.",
  "",
  `${sorted.length} packages.`,
  "",
];
for (const e of sorted) {
  lines.push(e.title, `  License: ${e.license}`);
  if (e.url) lines.push(`  Source: ${e.url}`);
  if (!e.files.length) lines.push("  No license file in the package. The SPDX license above applies.");
  for (const [name, text] of e.files) {
    const h = createHash("sha256").update(text).digest("hex");
    if (!texts.has(h)) texts.set(h, { n: texts.size + 1, text });
    lines.push(`  ${name}: text ${texts.get(h).n}`);
  }
  lines.push("");
}
for (const { n, text } of texts.values()) lines.push("=".repeat(78), `Text ${n}`, "=".repeat(78), "", text, "");
const body = lines.join("\n");

if (process.argv.includes("--check")) {
  const now = existsSync(out) ? readFileSync(out, "utf8").replace(/\r\n/g, "\n") : "";
  if (now !== body) {
    console.error("THIRD-PARTY-NOTICES.txt is out of date. Run: node scripts/third-party-notices.mjs");
    process.exit(1);
  }
  console.log(`THIRD-PARTY-NOTICES.txt is current (${sorted.length} packages, ${texts.size} texts).`);
} else {
  writeFileSync(out, body);
  console.log(`Wrote ${out} (${sorted.length} packages, ${texts.size} texts).`);
}
